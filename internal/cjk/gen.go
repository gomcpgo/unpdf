//go:build ignore

// This program builds the data files in data/ from the cid2code.txt tables
// of Adobe's cmap-resources project (https://github.com/adobe-type-tools/cmap-resources,
// BSD-3-Clause). Run it from this directory:
//
//	go run gen.go /path/to/cmap-resources
//
// For each character collection it writes one compressed file holding the
// CID-to-Unicode table and, for every legacy (non-Unicode) CMap of the
// collection, its code-to-CID table. See data.go for the format.
package main

import (
	"bufio"
	"bytes"
	"compress/flate"
	"encoding/binary"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type collection struct {
	dir     string   // directory in cmap-resources
	name    string   // output file and registry-ordering name
	unicode []string // columns to take Unicode from, best first
}

var collections = []collection{
	{"Adobe-Japan1-7", "Adobe-Japan1", []string{"UniJIS-UTF32", "UniJIS2004-UTF32", "UniJISX0213-UTF32", "UniJISX02132004-UTF32", "UniJIS-UCS2", "UniJIS-UCS2-HW"}},
	{"Adobe-GB1-6", "Adobe-GB1", []string{"UniGB-UTF32", "UniGB-UCS2"}},
	{"Adobe-CNS1-7", "Adobe-CNS1", []string{"UniCNS-UTF32", "UniCNS-UCS2"}},
	{"Adobe-Korea1-2", "Adobe-Korea1", []string{"UniKS-UTF32", "UniKS-UCS2"}},
	{"Adobe-KR-9", "Adobe-KR", []string{"UniAKR-UTF32"}},
}

// Columns that are not CMaps a PDF font can name as its encoding.
var skip = map[string]bool{"CID": true, "Hiragana": true, "Katakana": true, "Hankaku": true, "Roman": true, "WP-Symbol": true}

type pair struct {
	n    int
	code uint32
	cid  uint32
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run gen.go /path/to/cmap-resources")
		os.Exit(2)
	}
	var index []string
	for _, c := range collections {
		names := build(os.Args[1], c)
		for _, n := range names {
			index = append(index, fmt.Sprintf("\t%q: %q,", n, c.name))
		}
	}
	sort.Strings(index)
	src := "// Code generated by gen.go. DO NOT EDIT.\n\npackage cjk\n\n" +
		"// legacyCollection maps the name of a legacy CMap, without its -H or -V\n// suffix, to the character collection it belongs to.\n" +
		"var legacyCollection = map[string]string{\n" + strings.Join(index, "\n") + "\n}\n"
	formatted, err := format.Source([]byte(src))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("index.go", formatted, 0o644); err != nil {
		panic(err)
	}
}

func build(root string, c collection) []string {
	f, err := os.Open(filepath.Join(root, c.dir, "cid2code.txt"))
	if err != nil {
		panic(err)
	}
	defer f.Close()

	var header []string
	var uni []rune
	maps := map[string][]pair{}
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") || line == "" {
			continue
		}
		fields := strings.Split(line, "\t")
		if header == nil {
			header = fields
			continue
		}
		cid64, err := strconv.ParseUint(fields[0], 10, 32)
		if err != nil {
			continue
		}
		cid := uint32(cid64)
		for len(uni) <= int(cid) {
			uni = append(uni, 0)
		}
		col := func(name string) string {
			for i, h := range header {
				if h == name && i < len(fields) {
					return fields[i]
				}
			}
			return "*"
		}
		for _, name := range c.unicode {
			if r := bestUnicode(col(name)); r != 0 {
				uni[cid] = r
				break
			}
		}
		for i, h := range header {
			if skip[h] || strings.HasPrefix(h, "Uni") || i >= len(fields) || fields[i] == "*" {
				continue
			}
			for _, v := range strings.Split(fields[i], ",") {
				if strings.HasSuffix(v, "v") {
					continue // a code that only the vertical CMap uses
				}
				code, err := strconv.ParseUint(v, 16, 32)
				if err != nil || len(v)%2 != 0 {
					continue
				}
				maps[h] = append(maps[h], pair{len(v) / 2, uint32(code), cid})
			}
		}
	}

	var raw bytes.Buffer
	put := func(v uint64) { raw.Write(binary.AppendUvarint(nil, v)) }
	zigzag := func(v int64) uint64 { return uint64(v<<1) ^ uint64(v>>63) }

	raw.WriteString("UCJK1")
	put(uint64(len(uni)))
	prev := rune(0)
	for _, r := range uni {
		if r == 0 {
			put(0)
			continue
		}
		put(zigzag(int64(r-prev)) + 1)
		prev = r
	}
	var names []string
	for name := range maps {
		names = append(names, name)
	}
	sort.Strings(names)
	put(uint64(len(names)))
	for _, name := range names {
		ps := maps[name]
		sort.Slice(ps, func(i, j int) bool {
			if ps[i].n != ps[j].n {
				return ps[i].n < ps[j].n
			}
			return ps[i].code < ps[j].code
		})
		var body bytes.Buffer
		bput := func(v uint64) { body.Write(binary.AppendUvarint(nil, v)) }
		prevN, prevCode, prevCID := 0, uint32(0), uint32(0)
		for _, p := range ps {
			if p.n != prevN {
				prevN, prevCode = p.n, 0
			}
			body.WriteByte(byte(p.n))
			bput(uint64(p.code - prevCode))
			bput(zigzag(int64(p.cid) - int64(prevCID)))
			prevCode, prevCID = p.code, p.cid
		}
		put(uint64(len(name)))
		raw.WriteString(name)
		put(uint64(len(ps)))
		put(uint64(body.Len()))
		raw.Write(body.Bytes())
	}

	var out bytes.Buffer
	w, _ := flate.NewWriter(&out, flate.BestCompression)
	w.Write(raw.Bytes())
	w.Close()
	path := filepath.Join("data", c.name+".bin")
	if err := os.WriteFile(path, out.Bytes(), 0o644); err != nil {
		panic(err)
	}
	mapped := 0
	for _, r := range uni {
		if r != 0 {
			mapped++
		}
	}
	fmt.Printf("%-14s %6d CIDs (%d with Unicode), %2d legacy CMaps, %6d bytes compressed\n", c.name, len(uni), mapped, len(names), out.Len())
	return names
}

// bestUnicode picks one character from a Unicode column, which may list
// several values. Text extraction wants the ordinary character: for the
// glyph of a vertical comma that is the comma, not its vertical presentation
// form, and for an ideograph that doubles as a radical it is the ideograph.
// So values are ranked, and the first of the best rank wins. Values marked
// "v" are the ordinary characters that vertical glyphs stand for, and take
// part like any other.
func bestUnicode(field string) rune {
	if field == "*" || field == "" {
		return 0
	}
	best, bestRank := rune(0), 99
	for _, v := range strings.Split(field, ",") {
		n, err := strconv.ParseUint(strings.TrimSuffix(v, "v"), 16, 32)
		if err != nil || n == 0 || n > 0x10FFFF {
			continue
		}
		r := rune(n)
		rank := 0
		switch {
		case (r >= 0xE000 && r <= 0xF8FF) || r >= 0xF0000:
			rank = 2 // private use
		case (r >= 0x2E80 && r <= 0x2FDF) || // radicals
			(r >= 0xF900 && r <= 0xFAFF) || (r >= 0x2F800 && r <= 0x2FA1F) || // compatibility ideographs
			(r >= 0xFE10 && r <= 0xFE1F) || (r >= 0xFE30 && r <= 0xFE4F): // vertical presentation forms
			rank = 1
		}
		if rank < bestRank {
			best, bestRank = r, rank
		}
	}
	return best
}
