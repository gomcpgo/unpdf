//go:build ignore

// This program builds std14.go from Adobe's Core 14 AFM files: the glyph
// widths of the standard fonts that a PDF may use without embedding them or
// giving their widths. Run it from this directory:
//
//	go run gen_std14.go /path/to/afm-directory
//
// Courier is left out: every glyph is 600 units wide.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/gomcpgo/unpdf/internal/glyphs"
)

var fonts = []string{
	"Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
	"Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
	"Symbol", "ZapfDingbats",
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run gen_std14.go /path/to/afm-directory")
		os.Exit(2)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by gen_std14.go from Adobe's Core 14 AFM files. DO NOT EDIT.\n\npackage font\n\n")
	out.WriteString("// std14Widths holds, for each standard font, its glyph widths as sorted\n")
	out.WriteString("// values of character<<16 | width, the width in thousandths of an em.\n")
	out.WriteString("var std14Widths = map[string][]uint32{\n")
	for _, name := range fonts {
		f, err := os.Open(filepath.Join(os.Args[1], name+".afm"))
		if err != nil {
			panic(err)
		}
		widths := map[rune]int{}
		sc := bufio.NewScanner(f)
		for sc.Scan() {
			// C 65 ; WX 667 ; N A ; B 14 0 654 718 ;
			line := sc.Text()
			if !strings.HasPrefix(line, "C ") {
				continue
			}
			var wx int
			var glyph string
			for _, part := range strings.Split(line, ";") {
				fields := strings.Fields(part)
				if len(fields) == 2 && fields[0] == "WX" {
					wx, _ = strconv.Atoi(fields[1])
				}
				if len(fields) == 2 && fields[0] == "N" {
					glyph = fields[1]
				}
			}
			text, ok := glyphs.Name(glyph, name == "ZapfDingbats")
			if !ok {
				continue
			}
			if r := []rune(text); len(r) == 1 && r[0] <= 0xFFFF {
				if _, dup := widths[r[0]]; !dup {
					widths[r[0]] = wx
				}
			}
		}
		f.Close()
		var packed []uint32
		for r, w := range widths {
			packed = append(packed, uint32(r)<<16|uint32(w))
		}
		sort.Slice(packed, func(i, j int) bool { return packed[i] < packed[j] })
		fmt.Fprintf(&out, "\t%q: {", name)
		for i, v := range packed {
			if i%10 == 0 {
				out.WriteString("\n\t\t")
			}
			fmt.Fprintf(&out, "%#x, ", v)
		}
		out.WriteString("\n\t},\n")
		fmt.Printf("%-22s %d glyphs\n", name, len(packed))
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("std14.go", src, 0o644); err != nil {
		panic(err)
	}
}
